package me.ahoo.cosid.store.jdbc;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.SQLException;
import java.util.Objects;
import java.util.Optional;

/**
 * One borrowed connection of a JDBC store, as a {@link JdbcDialect} sees it: the connection in auto-commit mode, the
 * table names, and statements that carry the store timeout ({@code StoreConfig.timeout} as {@code queryTimeout}).
 */
public final class JdbcSession {
    private final Connection connection;
    private final JdbcTables tables;
    private final int queryTimeoutSeconds;
    private final Optional<String> readCommittedTransaction;

    JdbcSession(Connection connection, JdbcTables tables, int queryTimeoutSeconds, Optional<String> readCommittedTransaction) {
        this.connection = connection;
        this.tables = tables;
        this.queryTimeoutSeconds = queryTimeoutSeconds;
        this.readCommittedTransaction = readCommittedTransaction;
    }

    /**
     * The connection; in auto-commit mode outside {@link #transaction}.
     *
     * @return the connection
     */
    public Connection connection() {
        return connection;
    }

    /**
     * The table names of the store.
     *
     * @return the table names
     */
    public JdbcTables tables() {
        return tables;
    }

    /**
     * Prepares a statement with the store timeout.
     *
     * @param sql the SQL
     * @return the statement; the caller closes it
     * @throws SQLException if the driver fails
     */
    public PreparedStatement prepare(String sql) throws SQLException {
        return withTimeout(connection.prepareStatement(sql));
    }

    /**
     * Prepares a statement with the store timeout that reports generated keys.
     *
     * @param sql               the SQL
     * @param autoGeneratedKeys {@link java.sql.Statement#RETURN_GENERATED_KEYS} or {@code NO_GENERATED_KEYS}
     * @return the statement; the caller closes it
     * @throws SQLException if the driver fails
     */
    public PreparedStatement prepare(String sql, int autoGeneratedKeys) throws SQLException {
        return withTimeout(connection.prepareStatement(sql, autoGeneratedKeys));
    }

    private PreparedStatement withTimeout(PreparedStatement statement) throws SQLException {
        try {
            statement.setQueryTimeout(queryTimeoutSeconds);
        } catch (SQLException | RuntimeException e) {
            statement.close();
            throw e;
        }
        return statement;
    }

    /**
     * Runs {@code work} in one {@code READ COMMITTED} transaction (06 §2.1), then puts the auto-commit mode and the
     * isolation level of the pooled connection back ({@link JdbcDialect#readCommittedTransaction()}). Rolls back when
     * {@code work} throws.
     *
     * @param work the work
     * @param <T>  the result type
     * @return the result of {@code work}
     * @throws SQLException if the work or the driver fails
     */
    public <T> T transaction(SqlWork<T> work) throws SQLException {
        Objects.requireNonNull(work, "work");
        int isolation = readCommittedTransaction.isPresent() ? Connection.TRANSACTION_READ_COMMITTED : connection.getTransactionIsolation();
        if (isolation != Connection.TRANSACTION_READ_COMMITTED) {
            connection.setTransactionIsolation(Connection.TRANSACTION_READ_COMMITTED);
        }
        connection.setAutoCommit(false);
        try {
            if (readCommittedTransaction.isPresent()) {
                try (PreparedStatement statement = prepare(readCommittedTransaction.get())) {
                    statement.execute();
                }
            }
            T result = work.run();
            connection.commit();
            return result;
        } catch (SQLException | RuntimeException | Error e) {
            try {
                connection.rollback();
            } catch (SQLException rollback) {
                e.addSuppressed(rollback);
            }
            throw e;
        } finally {
            connection.setAutoCommit(true);
            if (isolation != Connection.TRANSACTION_READ_COMMITTED) {
                connection.setTransactionIsolation(isolation);
            }
        }
    }

    /**
     * Work on the connection of a session.
     *
     * @param <T> the result type
     */
    @FunctionalInterface
    public interface SqlWork<T> {
        T run() throws SQLException;
    }
}
