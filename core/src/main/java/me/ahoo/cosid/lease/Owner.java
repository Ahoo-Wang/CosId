package me.ahoo.cosid.lease;

import java.util.Objects;
import java.util.UUID;

/**
 * Who holds a slot lease (05-machine-lease.md §2).
 *
 * @param key         the logical identity, such as a host or pod name; only for sticky slot choice and observation
 * @param incarnation generated by each {@link LeaseKeeper} (each runtime) at start; distinct within one JVM too
 */
public record Owner(String key, UUID incarnation) {
    public Owner {
        Objects.requireNonNull(key, "key");
        Objects.requireNonNull(incarnation, "incarnation");
        if (key.isBlank()) {
            throw new IllegalArgumentException("key must not be blank");
        }
    }
}
